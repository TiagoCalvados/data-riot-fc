"""Generate English static assets from the shared Dutch source and reviewed catalogue.

Only source literals change at build time: names, team names and other runtime data
are never machine-translated. A single substitution pass prevents cascading matches.
Run this after updating templates or the catalogue; generated files are deployable.
"""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def build():
    translations = json.loads((ROOT / 'app/locales/en.json').read_text(encoding='utf-8'))
    pattern = re.compile('|'.join(re.escape(key) for key in sorted(translations, key=len, reverse=True)))
    def translate(source):
        return pattern.sub(lambda match: translations[match.group()], source)
    script = translate((ROOT / 'app/static/app.js').read_text(encoding='utf-8'))
    script = script.replace('const messageTranslations = {};', 'const messageTranslations = ' + json.dumps(translations, ensure_ascii=False) + ';')
    (ROOT / 'app/static/app.en.js').write_text('// Generated by scripts/build_locales.py.\n' + script, encoding='utf-8')
    html = translate((ROOT / 'app/static/index.html').read_text(encoding='utf-8'))
    html = html.replace('<html lang="nl">', '<html lang="en">').replace('/static/app.js', '/static/app.en.js')
    (ROOT / 'app/static/index.en.html').write_text(html, encoding='utf-8')


if __name__ == '__main__':
    build()
    print('Dutch and English assets ready.')
